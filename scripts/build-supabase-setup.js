// Combines every migration (in filename order) and the seed files into one script,
// server/supabase/setup-all.sql, to paste into the Supabase SQL Editor for a NEW
// project. Re-run after adding a migration:  node scripts/build-supabase-setup.js
const fs = require('fs');
const path = require('path');

const supabaseDir = path.resolve(__dirname, '..', 'server', 'supabase');
const migrationsDir = path.join(supabaseDir, 'migrations');
const outFile = path.join(supabaseDir, 'setup-all.sql');

// Migrations only. The seed files are left out: seed.sql is a psql \ir include (not
// valid in the SQL Editor), and seed_interview_questions.sql inserts the old
// English-only questions, superseded by the 16 bilingual questions that
// 20261020140300_bilingual_questions.sql seeds.
const parts = fs
  .readdirSync(migrationsDir)
  .filter(f => f.endsWith('.sql'))
  .sort()
  .map(f => path.join(migrationsDir, f));

const header = `-- TNV Hub: full database setup for a NEW Supabase project.
-- Generated by scripts/build-supabase-setup.js from ${parts.length} files. Do not edit by hand.
-- Paste the whole file into Supabase > SQL Editor and click Run.
`;

const body = parts
  .map(f => `\n-- ===== ${path.relative(supabaseDir, f).replace(/\\/g, '/')} =====\n${fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n').trim()}\n`)
  .join('');

fs.writeFileSync(outFile, header + body);
console.log(`Wrote ${path.relative(path.resolve(__dirname, '..'), outFile)} from ${parts.length} files`);
